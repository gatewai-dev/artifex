#!/usr/bin/env node
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const cliDir = path.resolve(__dirname, "..");
const repoRoot = path.resolve(cliDir, "../..");
const nodesDir = path.resolve(repoRoot, "nodes");
const outPath = path.join(cliDir, "src", "nodes-registry.ts");

function discoverNodes() {
	const entries = readdirSync(nodesDir).filter((d) => {
		const pkgPath = path.join(nodesDir, d, "package.json");
		if (!d.startsWith("node-") || !existsSync(pkgPath)) return false;
		try {
			const pkg = JSON.parse(readFileSync(pkgPath, "utf-8"));
			if (pkg.gatewai?.enabled === false) return false;
			if (!pkg.exports?.["./server"] && !pkg.exports?.["./renderer"])
				return false;
			return true;
		} catch {
			return false;
		}
	});

	return entries.map((d) => {
		const pkgPath = path.join(nodesDir, d, "package.json");
		const pkg = JSON.parse(readFileSync(pkgPath, "utf-8"));

		const metadataPath = path.join(nodesDir, d, "src", "metadata.ts");
		let nodeType = null;
		if (existsSync(metadataPath)) {
			const content = readFileSync(metadataPath, "utf-8");
			const match = content.match(/type:\s*["']([^"']+)["']/);
			if (match) nodeType = match[1];
		}

		return {
			dirName: d,
			packageName: pkg.name,
			nodeType,
			hasServer: !!pkg.exports?.["./server"],
			hasRenderer: !!pkg.exports?.["./renderer"],
		};
	});
}

const nodes = discoverNodes();

const serverRegistrations = [];
const rendererRegistrations = [];

const toVarName = (dir) => dir.replace(/-/g, "_");

for (const node of nodes) {
	const varName = toVarName(node.dirName);
	if (node.hasServer) {
		serverRegistrations.push(`\t\ttry {
			const ${varName} = await import("${node.packageName}/server");
			if (${varName}.default) registry.register(${varName}.default);
		} catch (e) {
			console.warn("Failed to register static node ${node.packageName}:", e);
		}`);
	}

	if (node.hasRenderer && node.nodeType) {
		rendererRegistrations.push(`\t\ttry {
			const mod = await import("${node.packageName}/renderer");
			const def = mod.default as
				| {
						WebGPURenderer?: Parameters<typeof registerWebGPURenderer>[1];
						audioProcessor?: Parameters<typeof audioRegistry.register>[1];
				  }
				| undefined;
			if (def?.WebGPURenderer) {
				registerWebGPURenderer("${node.nodeType}", def.WebGPURenderer);
			}
			if (def?.audioProcessor) {
				audioRegistry.register("${node.nodeType}", def.audioProcessor);
			}
		} catch (e) {
			console.warn("Failed to register static renderer for ${node.packageName}:", e);
		}`);
	}
}

const content = `// This file is auto-generated by scripts/generate-nodes-registry.mjs. Do not edit.
import type { NodeRegistry } from "@gatewai.studio/node-sdk/server";
import { registerWebGPURenderer, audioRegistry } from "@gatewai.studio/node-sdk/browser";

export async function registerStaticNodes(registry: NodeRegistry): Promise<void> {
${serverRegistrations.join("\n\n")}
}

export async function registerStaticRenderers(): Promise<void> {
${rendererRegistrations.join("\n\n")}
}
`;

writeFileSync(outPath, content, "utf-8");
console.log(
	`[generate-nodes-registry] Wrote static registry with ${nodes.length} nodes to ${outPath}`,
);
